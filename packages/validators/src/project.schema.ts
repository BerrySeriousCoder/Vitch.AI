/**
 * Nest clips use sourceSequenceId and must not carry media/text/shape content.
 * Enforced in editor-core validateSequences; this helper is for API/UI checks.
 */
export function isNestClipPayload(clip: {
  sourceSequenceId?: string | null;
  sourceMediaId?: string | null;
  textParams?: unknown;
  shapeParams?: unknown;
}): boolean {
  return Boolean(clip.sourceSequenceId);
}

