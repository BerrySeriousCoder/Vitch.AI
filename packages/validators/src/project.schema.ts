/** Schema for the `hsl-secondary` effect's partial qualifier/correction payload. */
export const hslSecondarySchema = z.object({
  hueCenter: z.number().finite().min(0).max(360).optional(),
  hueRange: z.number().finite().min(1).max(180).optional(),
  saturationMin: z.number().finite().min(0).max(1).optional(),
  saturationMax: z.number().finite().min(0).max(1).optional(),
  lightnessMin: z.number().finite().min(0).max(1).optional(),
  lightnessMax: z.number().finite().min(0).max(1).optional(),
  feather: z.number().finite().min(0).max(1).optional(),
  hueShift: z.number().finite().min(-180).max(180).optional(),
  saturationShift: z.number().finite().min(-100).max(100).optional(),
  lightnessShift: z.number().finite().min(-100).max(100).optional(),
  mix: z.number().finite().min(0).max(1).optional(),
}).strict().superRefine((value, context) => {
  if (value.saturationMin != null && value.saturationMax != null && value.saturationMin > value.saturationMax) {
    context.addIssue({ code: z.ZodIssueCode.custom, path: ["saturationMin"], message: "Saturation minimum cannot exceed maximum" });
  }
  if (value.lightnessMin != null && value.lightnessMax != null && value.lightnessMin > value.lightnessMax) {
    context.addIssue({ code: z.ZodIssueCode.custom, path: ["lightnessMin"], message: "Lightness minimum cannot exceed maximum" });
  }
});

